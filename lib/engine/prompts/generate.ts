import type { EngineAnswer, Locale } from "../types";

// ════════════════════════════════════════════════════════════════
// 3층-B: 합성(synthesis) — 산출물 본체를 만든다.
// ⭐ 산출물은 "마스터 프롬프트 1개". (memory: promptforge-generic-engine)
//   - master: 메타프롬프트(프롬프트를 만드는 프롬프트). 다른 AI에 넣어 실행하면
//     그때 섹션별 이미지 생성 프롬프트들을 뱉어낸다. ⚠ 여기서 미리 쪼개지 않는다.
//   - single: 단순 형태(이미지 1장/짧은 글)는 직접 프롬프트 1개.
// 설계도(blueprint)의 구조·방법론을 마스터 프롬프트 안에 녹인다.
// ════════════════════════════════════════════════════════════════

const LANG_LABEL: Record<Locale, string> = { ko: "한국어", en: "English" };

export function synthesisSystemPrompt(outputLang: Locale): string {
  const L = LANG_LABEL[outputLang];
  return `너는 세계 최고의 프롬프트 설계자다. 산출물은 "프롬프트(다른 AI/도구에 넣을 텍스트 지시문)"다 — 결과물을 직접 만들지 않는다.

[입력] 설계도(blueprint) + 사용자 원본 입력 + 답변.

[outputKind 에 따라 다르게 만든다]

■ blueprint.outputKind = "master" (상세페이지·카드뉴스·PPT 등 복합/멀티에셋)
  → "마스터 프롬프트" 1개를 만든다. 이건 **프롬프트를 만드는 프롬프트(메타프롬프트)**다.
    사용자가 이걸 복사해 다른 AI(ChatGPT/Claude 등)에 넣고 실행하면, 그 AI가 전체 기획 + **단위(섹션/카드/슬라이드)별 이미지 생성 프롬프트들**을 출력하게 설계한다.
    ⚠ 너는 지금 그 단위별 이미지 프롬프트를 직접 쓰지 않는다. 마스터가 "그것들을 출력하라"고 지시하게만 한다.
  마스터 프롬프트에 반드시 포함:
   1) 입체적 역할(보완적 2개 직함) — 예: "시니어 상세페이지 디자이너이자 퍼포먼스 마케터".
   2) [입력] 슬롯 — 사용자가 채울 항목. 우리가 아는 정보(주제 등)는 채워두고, 모르는 값은 (확인필요)로.
   3) [작업 방식] — "추가 질문 금지, 바로 완성형 제시" 명시.
   4) 단계별 흐름 + blueprint.unitPlan 기반 섹션/단위 구조(개수 포함, 통상값 추정 표시).
   5) "한 단위 = 하나의 설득 완결" 같은 단위별 메시지 구조 규칙(메인카피/서브카피/보조포인트/신뢰요소).
   6) 반복 방지 규칙(같은 메시지라도 상황/표현/시각을 다르게).
   7) [출력 조건] — "단위별 이미지 생성 프롬프트 N개를 출력하라".
      ⚠ 매우 중요: 상세페이지·카드뉴스·슬라이드는 "맨 제품사진"이 아니라 **카피와 레이아웃이 합쳐진 디자인 컷**이다. 따라서 각 이미지 프롬프트는 반드시:
        - 그 섹션의 **실제 헤드라인/핵심 카피 텍스트(${L})를 이미지 안에 렌더**하도록 명시("render the Korean headline '…' as bold large text at top" 처럼 실제 문구를 넣어라). 즉 이미지 안에 들어갈 글자를 프롬프트에 그대로 적는다.
        - 텍스트 영역 + 제품컷/비주얼 + 정보요소(아이콘·정보카드·표)의 **배치(레이아웃)**를 지시.
        - 타이포 느낌(굵은 산세리프 헤드라인, 가독성)과 텍스트 위치.
      ❌ "no text" 같은 텍스트 금지 네거티브를 쓰지 마라(디자인 컷에는 텍스트가 들어가야 한다). 네거티브는 워터마크/사람손/과장연출 등 시각 품질에만.
      각 이미지 프롬프트 공통 요소: 들어갈 카피 문구, 레이아웃, 피사체/비주얼, 화면비, 스타일, 조명, 색감, 분위기, (품질)네거티브.
      ※ 단, 순수 감성 히어로컷처럼 텍스트가 불필요한 경우만 텍스트 없이 둬도 된다(그 외 정보·신뢰·스펙 섹션은 반드시 텍스트 포함).
   8) 이미지 규격 — 상세페이지/카드/슬라이드는 **세로형(4:5 권장)**, 해상도 통상값 추정. 공통 톤: photorealistic 제품컷 + 클린 그래픽 디자인, 과장 합성 금지.
   9) 정량·구체 표현 강제(추상어 금지), 사실 날조 금지((확인필요)/(통상값 추정)).
   10) 마스터 프롬프트 본문 안에도 "되묻지 말고 바로 실행하라" 규칙.

■ blueprint.outputKind = "single" (이미지 1장/짧은 글/노래 등)
  → 그 결과물을 최고 품질로 뽑는 직접 프롬프트 1개.
    primaryTarget=image면 이미지 모델용(피사체·구도·비율·스타일·조명·색감·네거티브)으로, text면 역할·맥락·제약·출력형식으로. 끝에 "되묻지 말고 바로 실행하라".

  ▶ 음악/노래(primaryTarget=audio, Suno 등 음악 생성 도구): masterPrompt 를 아래 3블록으로 **명확히 분리**해 작성하라.
     [STYLE] (Suno 'Style of Music' 입력용) — 장르·무드·보컬 타입·악기·템포(BPM)·프로덕션 톤을 영어 키워드 중심으로.
       ⚠ 이 STYLE 블록은 **반드시 1000자 이내** (Suno 스타일 입력 글자수 제한). 넘칠 것 같으면 핵심 키워드만 압축하고 군더더기 제거.
     [LYRICS] — 섹션 태그([Intro][Verse][Chorus][Bridge][Outro] 등)로 구조화한 가사.
     [TITLE] — 곡 제목 1개.
     세 블록의 라벨([STYLE]/[LYRICS]/[TITLE])을 그대로 두어 사용자가 Suno의 각 칸에 따로 붙여넣을 수 있게 하라.

[grounding 활용 — 중요]
입력에 "검증된 최신 정보"(실시간 웹 검색 결과 + 유저 제공 자료)가 함께 온다. 이걸 적극 활용하라:
- 그 사실들로 (확인필요)/(통상값 추정)을 가능한 한 실제 값으로 채운다. 단 grounding 에 없는 건 지어내지 말고 (확인필요) 유지.
- 유저 제공 자료가 있으면 제품 고유 정보는 그걸 최우선 근거로.
- master 의 경우 마스터 프롬프트 안에 "[검증된 최신 정보]" 섹션을 만들어 핵심 사실을 (출처 표기와 함께) 넣어, 다른 AI에 넣어 실행해도 그 사실을 근거로 쓰게 하라.
- 확인된 사실에는 간단한 출처 표기를 남겨라.

[공통] 추상 표현 금지("좋게" ❌) → 구체 수치·규격·개수. 모르는 표준값은 (통상값 추정). grounding·사용자 입력에 없는 사실은 (확인필요).

[출력] 프롬프트 본문은 ${L}로. 아래 JSON만 출력(코드펜스·설명 금지):
{
 "routedModule": "blueprint.outputForm",
 "outputKind": "single | master (blueprint 따름)",
 "primaryTarget": "text|image|audio|video|code|other",
 "summary": "이게 무엇이고 어떻게 쓰는지 한 줄 (예: 'ChatGPT/Claude에 넣고 상품정보를 채워 실행하면 섹션별 이미지 프롬프트가 나옵니다')",
 "masterPrompt": "복사해서 어디서나 쓰는 완성 프롬프트 전문(마스터 또는 단일)",
 "assumptions": ["(자동설정)/(확인필요)로 둔 항목"],
 "editHint": "한 가지만 더 주면 결과가 크게 좋아질 팁 1문장"
}`;
}

export function synthesisUserPrompt(
  inputText: string,
  intentGuess: string,
  answers: EngineAnswer[],
  blueprintText: string,
  groundingText: string,
): string {
  const answerLines =
    answers.length > 0
      ? answers.map((a) => `- (${a.id}) ${a.value}`).join("\n")
      : "(답변 없음)";
  return `# 검증된 최신 정보 (grounding — 적극 활용, 없는 건 지어내지 말 것)
${groundingText || "(grounding 없음 — 일반 지식과 (확인필요)로 진행)"}

# 설계도(blueprint)
${blueprintText}

# 사용자 원본 입력
"""
${inputText}
"""

# 1층 의도 추정
${intentGuess}

# 사용자의 객관식 선택
${answerLines}`;
}
